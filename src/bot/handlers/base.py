from aiogram import Router
from aiogram.filters import CommandStart, Command
from aiogram.types import Message

from src.domain.forest_rules import MITTENS, ZONE_TO_MITTENS

router = Router(name="base_router")


@router.message(CommandStart())
async def cmd_start(message: Message) -> None:

    text = (
        "🌲 **Привіт! Я Мишка-шкряботушка** — хранителька Лісового архіву! 🐭📚\n\n"
        "Я допомагаю мешканцям наших **8 рукавичок** розбиратися з правилами, статутами ОСББ та корисними порадами для життя в лісі.\n\n"
        "🔍 **Як знайти пораду?**\n"
        "Просто напиши мені звичайне питання українською із зазначенням місця, наприклад:\n"
        "• *«Скільки внесок під дубом?»*\n"
        "• *«Які небезпеки в хвойному лісі?»*\n"
        "• *«Коли відкривають боброву греблю?»*\n"
        "• *«Які загальні правила толоки в лісі?»*\n\n"
        "📄 **Як додати свою пораду?**\n"
        "Просто надішли мені файл у форматі **PDF**, **Word (.docx)** або **TXT**. Якщо ти надсилаєш документ вперше — я запитаю твоє справжнє ім'я, щоб завжди вказувати автора!\n\n"
        "📍 Команда /places — подивитися список усіх рукавичок і частин лісу.\n"
        "ℹ️ Команда /help — коротка довідка."
    )
    await message.answer(text, parse_mode="Markdown")


@router.message(Command("help"))
async def cmd_help(message: Message) -> None:

    text = (
        "ℹ️ **Довідка помічника Лісового архіву:**\n\n"
        "1. **Запитання:** Пиши питання звичайними словами. Обов'язково вказуй, про яку рукавичку чи частину лісу питаєш.\n"
        "2. **Відповіді:** Я відповідаю суворо за документами з архіву і обов'язково називаю документ, а для порад від звірів — ще й автора та дату.\n"
        "3. **Нові документи:** Надсилай файли сюди. Я сама зрозумію, для якої вони рукавички (а якщо буде незрозуміло — ввічливо перепитаю).\n"
        "4. **Оновлення:** Нові версії правил автоматично замінюють старі."
    )
    await message.answer(text, parse_mode="Markdown")


